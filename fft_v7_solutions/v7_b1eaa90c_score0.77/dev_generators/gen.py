def main():
    kernels.reset()
    parts = [HDR]
    for L in SIZES:
        if cfg_scheme(L) == 'soa':
            P1 = r8(L); P2 = L*P1
            parts.append(kernels.gen_inst(L, f"f{L}_cb", P1//8, 1, False))
            parts.append(kernels.gen_inst(L, f"f{L}_k3", P2//8, P2//8, True, pwfn="pw_"+("sqrtnr" if cfg_pw(L) in ("sqrtnr","newton") else "alt")))
            parts.append(gen_slab(L))
            if L in (13, 17, 23, 36, 45, 64):
                parts.append(kernels.gen_halfmatrix2_inst(L, f"f{L}_z", 1, 1, False) if cfg_hm2(L) else kernels.gen_inst(L, f"f{L}_z", 1, 1, False, HU=cfg_hu(L)))
                parts.append(kernels.gen_halfmatrix2_inst(L, f"f{L}_y", L, L, False) if cfg_hm2(L) else kernels.gen_inst(L, f"f{L}_y", L, L, False, HU=cfg_hu(L)))
                parts.append(kernels.gen_halfmatrix2_inst(L, f"f{L}_x", L*L, L*L, True, pwfn="pw_"+cfg_pw(L)) if cfg_hm2(L) else kernels.gen_inst(L, f"f{L}_x", L*L, L*L, True, PF=cfg_pf(L), pwfn="pw_"+cfg_pw(L), HU=cfg_hu(L)))
                parts.append(gen_soa(L, True))
            else:
                code, _ = codelets.gen_core(L)
                parts.append(code)
                parts.append(gen_soa(L, False))
        elif cfg_scheme(L) == 'sq':
            G = {36:6, 64:8}[L]
            P1 = r8(L); P2 = L*P1 + (8 if L == 64 else 0)
            P1V, P2V = P1//8, P2//8
            parts.append(f"static V slabts{L}_r[{P1*P1V}], slabts{L}_i[{P1*P1V}];")
            if L == 64:
                parts.append(kernels.gen_zline64("f64_zline"))
                parts.append(kernels.gen_inst(64, "f64_ycol", P1V, P1V, False))
                parts.append(kernels.gen_sq_stage2_fz64("f64_s2z", P2V, P2V, PWPAT=CONFIG.get("sqpw",{}).get("64","sn")))
            if int(CONFIG.get('sqpar', {}).get(str(L), 0)):
                parts.append(kernels.gen_inst(L, f"f{L}_cbs", P1V, P1V, False))
                parts.append(gen_sq_extractp(L))
            parts.append(kernels.gen_inst(L, f"f{L}_cb", P1V, 1, False, INL=int(CONFIG.get("inl",{}).get(str(L),0))))
            parts.append(kernels.gen_sq_stage2(L, G, f"f{L}_s2", P2V, L*P1V, P2V, PF=cfg_pf(L), PWPAT=CONFIG.get("sqpw",{}).get(str(L),"sn")))
            parts.append(kernels.gen_sq_stage2(L, G, f"f{L}_s2e", P2V, L*P1V, G*P2V, PF=cfg_pf(L), PWPAT=CONFIG.get("sqpw",{}).get(str(L),"sn")))
            parts.append(kernels.gen_sq_stage1(L, G, f"f{L}_s1", P2V, P2V, L*P1V, PF=0, NT=int(CONFIG.get("nt",{}).get(str(L),0))))
            parts.append(kernels.gen_sq_stage1(L, G, f"f{L}_s1p", G*P2V, P2V, L*P1V, PF=cfg_pf(L)))
            parts.append(gen_sq_extract(L))
            parts.append(gen_sq(L, G))
        elif cfg_scheme(L) == 'apfa2':
            assert L == 45
            P1 = r8(45); P2 = 45*P1
            P1V, P2V = P1//8, P2//8
            parts.append(kernels.gen_inst(45, "f45_cb", P1V, 1, False, INL=int(CONFIG.get("inl",{}).get("45",0))))
            if int(CONFIG.get('sqpar', {}).get('45', 0)):
                parts.append(kernels.gen_inst(45, "f45_cbs", P1V, P1V, False))
                parts.append(gen_sq_extractp(45).replace("slab45_extractp", "slab45x_extractp"))
            parts.append(kernels.gen_sq_stage2(45, 5, "f45e_s2", P2V, 45*P1V, P2V, PF=0, PWPAT=CONFIG.get("sqpw",{}).get("45","sn")))
            parts.append(kernels.gen_sq_stage2(45, 9, "f45o_s2", P2V, 45*P1V, P2V, PF=0, PWPAT=CONFIG.get("sqpw",{}).get("45","sn")))
            parts.append(kernels.gen_pfa_stage1_tab(45, 5, "f45e_s1", P2V, 45*P1V, 9*P2V))
            parts.append(kernels.gen_pfa_stage1_tab(45, 9, "f45o_s1", P2V, 45*P1V, 5*P2V))
            parts.append(gen_sq_extract(45).replace("slab45_extract", "slab45x_extract"))
            parts.append(gen_apfa2_45())
        elif cfg_scheme(L) == 'apfa':
            assert L == 45
            P1 = r8(45); P2 = 45*P1
            P1V, P2V = P1//8, P2//8
            parts.append(kernels.gen_inst(45, "f45_cb", P1V, 1, False, INL=int(CONFIG.get("inl",{}).get("45",0))))
            parts.append(kernels.gen_sq_stage2(45, 5, "f45_s2d", P2V, 45*P1V, 9*P2V, PF=cfg_pf(45)))
            parts.append(kernels.gen_sq_stage2(45, 5, "f45_s2t", P2V, 45*P1V, P2V, PF=0))
            parts.append(kernels.gen_pfa_stage1_tab(45, 9, "f45_s1", P2V, 45*P1V, 5*P2V))
            parts.append(gen_sq_extract(45).replace("slab45_extract", "slab45x_extract"))
            parts.append(gen_apfa45())
        else:
            P1 = r8(L); P2 = L*P1 + (8 if L == 64 else 0)
            parts.append(kernels.gen_inst(L, f"f{L}_cb", P1//8, 1, False, HU=cfg_hu(L)))
            parts.append(kernels.gen_inst(L, f"f{L}_k3", P2//8, P2//8, True, PF=cfg_pf(L), pwfn="pw_"+cfg_pw(L), HU=cfg_hu(L)))
            parts.append(gen_slab(L))
    src = "\n".join(parts)
    # page-fault warmup of all static V arrays at dlopen (import time, untimed)
    import re as _re
    names = []
    for m in _re.finditer(r"static V (\w+)\[", src):
        if m.group(1) not in names:
            names.append(m.group(1))
    warm = "\n".join(f"  memset({n}, 0, sizeof({n}));" for n in names)
    src += f"\n__attribute__((constructor)) static void _warm_bss(void) {{\n{warm}\n}}\n"
    open("../implementation.c", "w").write(src)
    print(f"wrote implementation.c: {len(src.splitlines())} lines ({len(names)} arrays warmed)")

if __name__ == "__main__":
    main()
