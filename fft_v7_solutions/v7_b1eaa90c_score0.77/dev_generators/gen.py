def gen_soa(L, use_inst):
    THRESH = int(CONFIG.get('soathresh', {}).get(str(L), 5))
    K3PF = int(CONFIG.get('k3pf', {}).get(str(L), 0))
    pwfn_ = cfg_pw(L)
    if pwfn_ == 'alt':
        pwdef = '#define PW68SEL ((i & 1) ? pw_newton(zr, zi) : pw_sqrtnr(zr, zi))'
    else:
        pwdef = f'#define PW68SEL pw_{pwfn_}(zr, zi)'
    L2, L3 = L*L, L*L*L
    if use_inst:
        passz = f"f{L}_z(sr + y*{L}, si + y*{L}, sr + y*{L}, si + y*{L});"
        passy = f"f{L}_y(sr + z, si + z, sr + z, si + z);"
        passx = f"f{L}_x(soa{L}_xr + u, soa{L}_xi + u, soa{L}_xr + u, soa{L}_xi + u, soa{L}_cr + u, soa{L}_ci + u);"
    else:
        passz = f"fft{L}_core(sr + y*{L}, si + y*{L}, sr + y*{L}, si + y*{L}, 1, 1);"
        passy = f"fft{L}_core(sr + z, si + z, sr + z, si + z, {L}, {L});"
        pwbody = []
        for i in range(L):
            fn = ('pw_sqrtnr' if i % 2 == 0 else 'pw_newton') if cfg_pw(L) == 'alt' else 'pw_' + cfg_pw(L)
            pwbody.append(f"""          {{ long idx = u + {i}*{L2};
            V zr = tr[{i}] + soa{L}_cr[idx];
            V zi = ti[{i}] + soa{L}_ci[idx];
            V f = {fn}(zr, zi);
            soa{L}_xr[idx] = zr*f; soa{L}_xi[idx] = zi*f; }}""")
        pwb = chr(10).join(pwbody)
        passx = f"""{{
          V tr[{L}], ti[{L}];
          fft{L}_core(soa{L}_xr + u, soa{L}_xi + u, tr, ti, {L2}, 1);
{pwb}
        }}"""
    return f'''
{pwdef}
// ---------------- L={L} : SoA across 8 volumes ----------------
static V soa{L}_xr[{L3}], soa{L}_xi[{L3}], soa{L}_cr[{L3}], soa{L}_ci[{L3}];
static V soa{L}_or[{L3}], soa{L}_oi[{L3}];

static void soa{L}_grp(const double*restrict x0, const double*restrict c, long g0, int lanes, long m,
            double*restrict out1, double*restrict outm) {{
  {{
    for (long i = 0; i < {L3}; i++) {{
      V xr = VC(0.0), xi = VC(0.0), cr = VC(1.0), ci = VC(0.0);
      for (int l = 0; l < lanes; l++) {{
        long src = 2*((g0+l)*{L3} + i);
        xr[l] = x0[src]; xi[l] = x0[src+1];
        cr[l] = c[src];  ci[l] = c[src+1];
      }}
      soa{L}_xr[i] = xr; soa{L}_xi[i] = xi; soa{L}_cr[i] = cr; soa{L}_ci[i] = ci;
    }}
    for (long it = 0; it < m; it++) {{
      for (long x = 0; x < {L}; x++) {{
        V *sr = soa{L}_xr + x*{L2}, *si = soa{L}_xi + x*{L2};
        for (long y = 0; y < {L}; y++)
          {passz}
        for (long z = 0; z < {L}; z++)
          {passy}
      }}
      for (long u = 0; u < {L2}; u++) {{
        if ({K3PF} && (u & 7) == 0 && u + 8 < {L2}) {{
          for (long i = 0; i < {L}; i++) {{
            long a = u + 8 + i*{L2};
            __builtin_prefetch(soa{L}_xr + a, 1, 3); __builtin_prefetch(soa{L}_xi + a, 1, 3);
            __builtin_prefetch(soa{L}_cr + a, 0, 3); __builtin_prefetch(soa{L}_ci + a, 0, 3);
          }}
        }}
        {passx}
      }}
      if (it == 0) {{
        memcpy(soa{L}_or, soa{L}_xr, sizeof(soa{L}_or));
        memcpy(soa{L}_oi, soa{L}_xi, sizeof(soa{L}_oi));
      }}
    }}
    for (int l = 0; l < lanes; l++) {{
      double *d1 = out1 + 2*(g0+l)*{L3}, *dm = outm + 2*(g0+l)*{L3};
      for (long i = 0; i < {L3}; i++) {{
        d1[2*i] = soa{L}_or[i][l]; d1[2*i+1] = soa{L}_oi[i][l];
        dm[2*i] = soa{L}_xr[i][l]; dm[2*i+1] = soa{L}_xi[i][l];
      }}
    }}
  }}
}}

void run{L}(const double*restrict x0, const double*restrict c, long B, long m,
            double*restrict out1, double*restrict outm) {{
  long done = 0;
  while (B - done >= 8) {{ soa{L}_grp(x0, c, done, 8, m, out1, outm); done += 8; }}
  long rem = B - done;
  if (rem > 0) {{
    if (rem >= {THRESH})
      soa{L}_grp(x0, c, done, (int)rem, m, out1, outm);
    else
      for (long v = done; v < B; v++) slab{L}_one(x0, c, v, m, out1, outm);
  }}
}}
#undef PW68SEL
'''

def gen_slab(L):
    K3PF = int(CONFIG.get('k3pf', {}).get(str(L), 0))
    P1 = r8(L)
    P2 = L*P1 + (8 if L == 64 else 0)
    P1V, P2V = P1//8, P2//8
    NB = P1//8
    L3 = L*L*L
    return f'''
// ---------------- L={L} : per-volume slab scheme, always-natural (P1={P1}, P2={P2}) ----------------
static V slab{L}_xr[{L*P2V}], slab{L}_xi[{L*P2V}];
static V slab{L}_cer[{L*P2V}], slab{L}_cei[{L*P2V}];
static V slab{L}_1r[{L*P2V}], slab{L}_1i[{L*P2V}];
static V slab{L}_tsr[{P1*P1V}], slab{L}_tsi[{P1*P1V}];
static V slab{L}_br[2*{P1}], slab{L}_bi[2*{P1}];

static void slab{L}_iter(long m) {{
  for (long j = {L}; j < {P1}; j++) {{ slab{L}_br[j] = VC(0.0); slab{L}_bi[j] = VC(0.0);
    slab{L}_br[{P1}+j] = VC(0.0); slab{L}_bi[{P1}+j] = VC(0.0); }}
  for (long it = 0; it < m; it++) {{
    for (long x = 0; x < {L}; x++) {{
      V *sr = slab{L}_xr + x*{P2V}, *si = slab{L}_xi + x*{P2V};
      for (long cc = 0; cc < {NB}; cc++) {{
        V *br_ = slab{L}_br + (cc&1)*{P1}, *bi_ = slab{L}_bi + (cc&1)*{P1};
        f{L}_cb(sr + cc, si + cc, br_, bi_);
        for (long rb = 0; rb < {P1V}; rb++) {{
          V tb[8];
          tr8x8(br_ + rb*8, tb);
          for (int q = 0; q < 8; q++) slab{L}_tsr[(cc*8+q)*{P1V} + rb] = tb[q];
          tr8x8(bi_ + rb*8, tb);
          for (int q = 0; q < 8; q++) slab{L}_tsi[(cc*8+q)*{P1V} + rb] = tb[q];
        }}
      }}
      for (long cc = 0; cc < {NB}; cc++) {{
        V *br_ = slab{L}_br + (cc&1)*{P1}, *bi_ = slab{L}_bi + (cc&1)*{P1};
        f{L}_cb(slab{L}_tsr + cc, slab{L}_tsi + cc, br_, bi_);
        int lim = (int)({L} - cc*8); if (lim > 8) lim = 8;
        for (long rb = 0; rb < {P1V}; rb++) {{
          V tb[8];
          tr8x8(br_ + rb*8, tb);
          for (int q = 0; q < lim; q++) sr[(cc*8+q)*{P1V} + rb] = tb[q];
          tr8x8(bi_ + rb*8, tb);
          for (int q = 0; q < lim; q++) si[(cc*8+q)*{P1V} + rb] = tb[q];
        }}
      }}
    }}
    for (long o = 0; o < {L*P1V}; o++) {{
      if ({K3PF} && (o & 7) == 0 && o + 8 < {L*P1V}) {{
        for (long i = 0; i < {L}; i++) {{
          long a = o + 8 + i*{P2V};
          __builtin_prefetch(slab{L}_xr + a, 1, 3); __builtin_prefetch(slab{L}_xi + a, 1, 3);
          __builtin_prefetch(slab{L}_cer + a, 0, 3); __builtin_prefetch(slab{L}_cei + a, 0, 3);
        }}
      }}
      f{L}_k3(slab{L}_xr + o, slab{L}_xi + o, slab{L}_xr + o, slab{L}_xi + o,
              slab{L}_cer + o, slab{L}_cei + o);
    }}
    if (it == 0) {{
      memcpy(slab{L}_1r, slab{L}_xr, sizeof(slab{L}_1r));
      memcpy(slab{L}_1i, slab{L}_xi, sizeof(slab{L}_1i));
    }}
  }}
}}

static void slab{L}_extract(const V*restrict ar, const V*restrict ai, double*restrict dst) {{
  const double *r = (const double*)ar, *im = (const double*)ai;
  for (long x = 0; x < {L}; x++)
    for (long y = 0; y < {L}; y++) {{
      const long rowr = x*{P2} + y*{P1};
      double *d = dst + 2*((x*{L} + y)*{L});
      for (long z = 0; z < {L}; z++) {{
        d[2*z]   = r[rowr + z];
        d[2*z+1] = im[rowr + z];
      }}
    }}
}}

static void slab{L}_one(const double*restrict x0, const double*restrict c, long v, long m,
            double*restrict out1, double*restrict outm) {{
  double *xr = (double*)slab{L}_xr, *xi = (double*)slab{L}_xi;
  double *cer = (double*)slab{L}_cer, *cei = (double*)slab{L}_cei;
  {{
    const double *sx = x0 + 2*v*{L3}, *sc = c + 2*v*{L3};
    for (long x = 0; x < {L}; x++)
      for (long y = 0; y < {L}; y++) {{
        long row = x*{P2} + y*{P1};
        const double *px = sx + 2*((x*{L}+y)*{L});
        const double *pc = sc + 2*((x*{L}+y)*{L});
        for (long z = 0; z < {L}; z++) {{
          xr[row+z] = px[2*z]; xi[row+z] = px[2*z+1];
          cer[row+z] = pc[2*z]; cei[row+z] = pc[2*z+1];
        }}
        for (long z = {L}; z < {P1}; z++) {{
          xr[row+z] = 0.0; xi[row+z] = 0.0;
          cer[row+z] = 1.0; cei[row+z] = 0.0;
        }}
      }}
    slab{L}_iter(m);
    slab{L}_extract(slab{L}_1r, slab{L}_1i, out1 + 2*v*{L3});
    slab{L}_extract(slab{L}_xr, slab{L}_xi, outm + 2*v*{L3});
  }}
}}
'''





