/* L13_dmma -- L = 13 on one A100.
 *
 * Round gpu_r3 adds the small-batch plane-split path: at batch <= 8 the transform
 * is ONE plain launch of 13*B blocks -- each block does dense per-output z+y DFTs of
 * one x-plane into a plan-owned scratch, all blocks join at a software grid barrier
 * (arrive-and-spin on a plan-owned monotonic u64 counter; single plain launch beats
 * cudaLaunchCooperativeKernel by ~1.4 us and a second launch by ~1.6 us), then each
 * block computes one output kx-plane with block-uniform broadcast twiddles.
 * Adopted from L17_dmma round gpu_r2 (their soft-barrier design, ported; epoch
 * counter, co-residency check in create() and two-launch-free fallback included).
 * B=1: 7.86 -> 6.78 us. The fused kernel and its __stcs selection are unchanged
 * from gpu_r2 and still carry all batched points.
 *
 * Round gpu_r2 added ONE production change: the final store is issued with __stcs
 * (evict-first) whenever the working set (in+out = 2*B*35152 B) is L2-resident, so
 * the output stream does not evict the input from L2 between the driver's timed
 * calls (adopted from L8_blockfused round gpu_r1). B=477: 28.4 -> 21.6 us/call.
 * The other kernels in this file (loadz, fused2, split, fusedx, wcp) are measured
 * dead ends kept behind L13_FORCE_* env knobs for future A/B work -- numbers in
 * strategies/L13_dmma.md; none is ever selected by default.
 *
 * Technique (round gpu_r1): fused single kernel, one 13^3 volume per block in shared
 * memory (35,152 B, natural stride 13 is odd so every pass is bank-conflict-free), one
 * thread per 13-point line, three axis passes separated by __syncthreads(), one global
 * read + one global write per volume. The line transform is the conjugate-symmetric
 * folded dense matvec from the CPU phase's L13_direct winner:
 *
 *     u_j = x_j + x_{13-j},  v_j = x_j - x_{13-j}            (j = 1..6)
 *     P_k = x_0 + sum_j cos(2 pi k j/13) u_j
 *     S_k =       sum_j sin(2 pi k j/13) v_j                 (k = 1..6)
 *     X_0 = x_0 + sum_j u_j,   X_k = P_k - i S_k,   X_{13-k} = P_k + i S_k
 *
 * ~29 real flop/point/axis: at B_HBM the arithmetic sits at ~0.6x the HBM floor on the
 * vanilla FP64 pipe, so DMMA (the entry's namesake) is held in reserve -- see the
 * strategy record for the arithmetic and the conditions under which it would pay.
 *
 * The x-axis pass reads shared and writes its results directly to global (coalesced:
 * fixed k, consecutive threads hit consecutive complex doubles), saving one full
 * shared-memory round trip of the volume.
 */
#include <cuda_runtime.h>
#include <cuda_pipeline.h>
#include <stdlib.h>

#include "../fft3d_gpu_api.h"

